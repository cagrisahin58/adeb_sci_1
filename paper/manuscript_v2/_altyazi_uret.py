#!/usr/bin/env python
"""Write paper/manuscript_v2/altyazilar_v2.tex from the installed v2 manifests' caption drafts.

    python paper/manuscript_v2/_altyazi_uret.py

Each installed figure paper/figures_v2/figN_<kok>.fig.json carries `altyazi_taslagi` (plain text with Unicode
symbols). The first sentence becomes the bold lead-in; symbols are rewritten to the manuscript's own LaTeX
(\\simt from macros_konsey.tex, \\eps from main.tex). The output maps each figure label to its v2 caption:
    \\altyazi{fig:<label>}{<caption>}
derle_v2.sh reads this file; the body text is never copied by hand.
"""
import io
import json
import re
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
FIG = HERE.parent / "figures_v2"
LABEL = {"study_overview": "study_overview", "design_recipe": "design_recipe",
         "decomposition_schematic": "decomposition_schematic", "panel_members": "panel_members",
         "registry_map": "registry_map", "prereg_chain": "prereg_chain", "source_gap_split": "source_gap_split",
         "similarity_matrix": "similarity_matrix", "cells_interaction": "cells_interaction",
         "attack_side": "attack_side", "gradient_alignment": "gradient_alignment",
         "estimates_forest": "estimates_forest", "protocol_settings": "protocol_settings",
         "protocol_sets": "protocol_sets", "spread_clean_gap": "spread_clean_gap", "epsilon_sweep": "epsilon_sweep",
         "feature_degradation": "feature_degradation"}
SUB = [
    ("log τ̄", r"$\log\simt$"), ("τ̄", r"$\simt$"),
    ("A(σ, scr)", r"$\Asig{scr}$"), ("I(σ)", r"$\Isig$"),
    ("A(ρ)", r"$\Arho$"),
    ("σ", r"$\sigma$"), ("ρ", r"$\rho$"), ("ε", r"$\eps$"),
    ("ω", r"$\omega$"), ("Δ", r"$\Delta$"), ("–", "--"),
    ("±", r"$\pm$"), ("×", r"$\times$"), ("−", r"$-$"), ("≥", r"$\geq$"), ("≤", r"$\leq$"),
    ("′", "$'$"), ("%", r"\%"),
]


def latex(s):
    for a, b in SUB:
        s = s.replace(a, b)
    s = s.replace("$$", "")
    return s


def main():
    out = ["% altyazilar_v2.tex: v2 figure captions keyed by label (generated by _altyazi_uret.py from the",
           "% installed manifests' altyazi_taslagi; do not edit by hand, edit the figure script and reinstall).", ""]
    for p in sorted(FIG.glob("fig*_*.fig.json"), key=lambda q: int(re.match(r"fig(\d+)_", q.name).group(1))):
        m = json.loads(p.read_text(encoding="utf-8"))
        kok = re.match(r"fig\d+_(.*)\.fig\.json", p.name).group(1)
        cap = m["altyazi_taslagi"].strip()
        lead, _, rest = cap.partition(". ")
        words = len(cap.split())
        if words > 60:
            sys.exit(f"{p.name}: caption has {words} words (limit 60)")
        tex = r"\textbf{" + latex(lead) + ".} " + latex(rest)
        out.append(f"\\altyazi{{fig:{LABEL[kok]}}}{{{tex}}}  % {words} words")
    io.open(HERE / "altyazilar_v2.tex", "w", encoding="utf-8", newline="\n").write("\n".join(out) + "\n")
    print("wrote", len(out) - 3, "captions")


if __name__ == "__main__":
    main()
