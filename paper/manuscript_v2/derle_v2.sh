#!/usr/bin/env bash
# derle_v2.sh: build the alternative manuscript main_v2.pdf with the Üslup Z figures (paper/figures_v2).
# Run in WSL from paper/manuscript_v2:  bash derle_v2.sh
# Single source: the body text is copied at build time from ../manuscript/sections/*.tex; only the figure paths
# (../figures/ -> ../figures_v2/) and the figure captions (from altyazilar_v2.tex, keyed by label) change.
# main_v2.tex is ../manuscript/main.tex with its input paths changed; the title is the same.
# The original manuscript (paper/manuscript) and the original figures (paper/figures) are never written.
set -euo pipefail
export PATH="/home/firat/.local/bin:${PATH}"
cd "$(dirname "$0")"
SRC=../manuscript
# 1. fresh copies of the sections and of the class, bibliography style, font and logo files
rm -rf sections
mkdir -p sections
cp "$SRC"/sections/*.tex sections/
for f in "$SRC"/*; do
  b=$(basename "$f")
  case "$b" in
    main.*|sections|pdflatex*.fls|references.bib.bak|*.md) ;;
    macros_konsey.tex|references.bib) cp "$f" . ;;
    *.cls|*.bst|*.png|*.map|*.pfb|*.tfm|*.fd) cp "$f" . ;;
  esac
done
# 2. main_v2.tex from main.tex (input paths stay relative: sections/ and macros_konsey are now local copies)
cp "$SRC/main.tex" main_v2.tex
sed -i '1i % main_v2.tex: generated by derle_v2.sh from ../manuscript/main.tex; only this comment differs; figures from ../figures_v2' main_v2.tex
# 3. figure paths and v2 captions in the copied sections
python3 _bolum_uygula.py
# 4. clean build from scratch
rm -f main_v2.aux main_v2.bbl main_v2.blg main_v2.fdb_latexmk main_v2.fls main_v2.log main_v2.out main_v2.pdf
latexmk -pdf -interaction=nonstopmode -halt-on-error main_v2.tex > derle_v2.log 2>&1 || { tail -30 derle_v2.log; exit 1; }
echo "pages: $(pdfinfo main_v2.pdf | awk '/^Pages/{print $2}')"
echo "undefined: $(grep -ci 'undefined' main_v2.log || true)"
echo "overfull: $(grep -c 'Overfull' main_v2.log || true)"
