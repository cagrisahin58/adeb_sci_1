#!/usr/bin/env python
"""Write the paper palette for one catalogue style: paper/figures/visio/palettes/adeb_konsey_uslup_<N>.yaml.

The entity colours are the paper's own semantic Okabe-Ito binding, read from
paper/figures/konsey/konsey_ortak.py (COL, MUTE); nothing is typed here. The structural
colours (ink, frame, grid, card tones) are the selected style's, taken from the palette
the skill derives for that style (motor/host/uslup_to_palette.py, written to a temporary
folder). Every entity gets a marker so that it stays identifiable without colour; the
markers of vit, r224 and mixed are the ones the council figures already print
(fig_gradient_alignment.py TYPES: '^', 'o', 's').

    python paper/figures/visio/_palet_uret.py --uslup 8
"""
from __future__ import annotations

import argparse
import io
import sys
import tempfile
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import _vz_ortam  # noqa: E402

_vz_ortam.kur()
sys.path.insert(0, "paper/figures/konsey")
import konsey_ortak as K  # noqa: E402
import yaml  # noqa: E402
from motor.figspec import cvd  # noqa: E402
from motor.figspec import palette as palette_mod  # noqa: E402
from motor.figspec import uslup as uslup_mod  # noqa: E402

OUT = Path("paper/figures/visio/palettes")
# entity key -> (family, label, marker, line style); hex from konsey_ortak
ENTITIES = {
    "vit": ("mimari", "ViT-Tiny / transformer", "^", "-"),
    "r224": ("mimari", "ResNet-18, 224 pipeline / CNN", "o", "-"),
    "r32": ("mimari", "ResNet-18, CIFAR stem (R32)", "D", "--"),
    "panel": ("mimari", "robust CNN panel member", "v", ":"),
    "xcit": ("mimari", "XCiT-S12 (secondary)", "P", "-."),
    "mixed": ("mimari", "mixed pair (CNN-transformer)", "s", "--"),
    "sym": ("bilesen", "symmetric part, sigma", "h", "-"),
    "dir": ("bilesen", "directional part, rho", "X", "--"),
}


def hex_of(key):
    return (K.MUTE if key == "mixed" else K.COL[key]).upper()


def uret(no: str) -> Path:
    u = uslup_mod.load_uslup(no, argv=[])
    with tempfile.TemporaryDirectory() as td:
        sp = uslup_mod.ensure_palette(u, Path(td))
        style_pal = yaml.safe_load(Path(sp).read_text(encoding="utf-8"))
    ents = {}
    for k, (fam, lab, mk, ls) in ENTITIES.items():
        ents[k] = {"hex": hex_of(k), "marker": mk, "ls": ls, "label": lab, "emphasis": "primary",
                   "aile": fam}
        if cvd.contrast_ratio(hex_of(k)) < palette_mod.MIN_CONTRAST:
            ents[k]["direct_label"] = True      # the skill's rule for a hue weak against white
    doc = {"paper": f"adeb_konsey_uslup_{u.no}",
           "kaynak": {"varliklar": "paper/figures/konsey/konsey_ortak.py COL, MUTE",
                      "konsey_ortak_sha256": K.sha("paper/figures/konsey/konsey_ortak.py"),
                      "yapisal": f"skill uslup_to_palette, uslup {u.no}"},
           "entities": ents, "structural": style_pal.get("structural", {})}
    OUT.mkdir(parents=True, exist_ok=True)
    p = OUT / f"adeb_konsey_uslup_{u.no}.yaml"
    with io.open(p, "w", encoding="utf-8", newline="\n") as fh:
        fh.write("# Generated by paper/figures/visio/_palet_uret.py; do not hand-edit.\n")
        yaml.safe_dump(doc, fh, allow_unicode=True, sort_keys=False)
    pal = palette_mod.load(str(p))
    rep = palette_mod.validate_binding(pal)
    print(f"wrote {p}: {len(pal.entities)} entities, {len(pal.structural)} structural, "
          f"{len(rep['warnings'])} warning(s)")
    for w in rep["warnings"]:
        print("  warning:", w)
    return p


def main():
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--uslup", nargs="+", required=True)
    a = ap.parse_args()
    for n in a.uslup:
        uret(n)


if __name__ == "__main__":
    main()
